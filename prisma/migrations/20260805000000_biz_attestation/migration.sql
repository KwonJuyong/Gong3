-- 발주 권한 확인 기록 (2026-08-05).
--
-- ## 왜 필요했나
--
-- 같은 날 발주·견적서 게이트를 `role === "DEVELOPER"` 에서 **유효한 사업자등록번호 보유**로
-- 바꿨다. role 은 가입 폼에서 "게스트"를 누르면 붙는 자칭이었고, 사업자번호는 체크섬으로
-- 형식이 검증되고 팝빌로 휴폐업까지 대조되므로 **더 강한 게이트다.**
--
-- 다만 사업자등록번호는 **공개 정보라 소유 증명이 아니다.** 남의 번호를 적을 수 있다.
-- 발주는 세금계산서·대금청구가 그 번호로 가니 실익이 없지만, **견적서는 우리 상호·
-- 사업자번호·직인이 찍힌 문서가 나간다.**
--
-- 이 컬럼은 그걸 **막지 못한다.** 대신 남의 번호 입력을 '실수'에서 '명시적 허위 진술'로
-- 바꾼다. 기록이 없으면 고지한 적이 있다는 근거 자체가 없다.
--
-- ## 🔴 게이트가 아니다 — 그래서 backfill 하지 않는다
--
-- `canTransact()` 는 이 값을 **보지 않는다.** 보게 만들면 이 컬럼이 생기기 전에 등록한
-- 기업이 배포 즉시 발주에서 잠긴다 — `emailVerifiedAt`·평가 grandfather 와 같은 함정이다.
--
-- 그리고 **기존 행을 채우지도 않는다.** 그들은 실제로 확인한 적이 없다.
-- `emailVerifiedAt = createdAt` 같은 backfill 을 여기 흉내 내면 "확인받았다"는 거짓 기록이
-- 남고, 그러면 이 컬럼의 유일한 존재 이유(근거가 된다는 것)가 사라진다.
-- NULL = "아직 확인 안 받음" 이고, 다음번 기업 정보 저장 때 자연스럽게 채워진다.

