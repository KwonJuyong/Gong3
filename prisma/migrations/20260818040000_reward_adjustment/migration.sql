-- ## 무엇이 문제였나
--
-- `Order` 는 `panelSize × rewardPerPerson` **한 쌍**만 저장하고, `createRewardForResponse`
-- 는 그 단가를 모두에게 똑같이 준다. 회차가 둘 이상이면 발주 폼이 아예 잠긴다.
--
-- 그런데 첫 실거래(클라썸)의 실제 편차는 **회차가 아니라 사람**이었다:
--
--     1회차 — 4시간 3명(41,280원) + 2시간 1명(20,640원)
--
-- 견적서는 이걸 `41,280원 × 3명` 한 줄로 적었고 **2시간 참여자 1명이 통째로 빠졌다**
-- (청구 835,920 vs 실제 지급 대상 856,560, 차이 20,640 = 정확히 그 한 명).
-- 결국 그 건은 플랫폼 밖에서 손으로 정산됐다.
--
-- ## 🔴 회차 단위(OrderItem)로 쪼개도 안 된다
--
-- 원래 계획은 `OrderItem` 을 만들어 다항목 발주를 지원하는 것이었다. **그걸로는 위 사람을
-- 여전히 못 담는다** — 편차의 축이 회차가 아니라 사람이기 때문이다. 게다가
-- `Order.projectId` 가 `@unique` 라 한 발주가 여러 회차(=여러 Project)를 갖게 하려면
-- 보상 생성·환불 계산·정원 판정까지 함께 바꿔야 하는 큰 수술이 된다.
--
-- 그래서 **발주 구조는 그대로 두고 개인 보상액을 검수 단계에서 조정**할 수 있게 한다.
-- 훨씬 작은 변경으로 실제 문제를 덮는다.
--
-- ## ⚠ 어긋남을 숨기지 않는다
--
-- 조정하면 `Σ Reward.grossAmount` 와 `Order.subtotal` 이 달라진다. 이건 **감출 게 아니라
-- 봐야 하는 신호**다 — "기업에 청구한 금액과 학생에게 지급할 금액이 다르다"는 뜻이고,
-- 클라썸의 누락 20,640원도 이 신호로 잡혔을 것이다. 화면이 차액을 표시한다.
--
-- ⚠ 조정은 **지급 전(PENDING)** 에만 가능하다. 이미 이체된 건의 금액을 바꾸면 원장·통장과
--   어긋나고, 신고 자료는 지급 시점 스냅샷이라 이미 나간 신고와도 어긋난다.

