-- 관리자 세션 일괄 무효화 (2026-09-02).
--
-- ## 왜 필요한가
--
-- 같은 배포에서 세션 수명을 권한별로 갈랐다(관리자 8시간 / 그 외 30일, `app/session.ts`
-- `sessionTtlFor`). 그런데 **이미 발급된 쿠키는 그 규칙을 모른다** — 옛 형식에는 수명
-- 필드가 없어서 검증기가 기본값(30일)으로 받아주고, middleware 는 Edge 라 role 을 볼 수
-- 없어 갱신 때도 30일 그대로 이어간다.
--
-- 즉 **이 변경의 대상인 "지금 열려 있는 관리자 세션"이 정확히 그 변경을 비껴간다.**
-- 실습실·공용 PC 에 남아 있을 수 있는 세션이 바로 그것이고, 그게 이 작업을 시작한 이유다.
-- 수명이 짧아지는 건 다음 로그인부터인데, 로그아웃을 안 했으니 다음 로그인도 없다.
--
-- ## 그래서 한 번 끊는다
--
-- `sessionEpoch` 를 올리면 그 계정의 모든 세션이 즉시 무효가 된다(`getSessionUserId` 가
-- DB 값과 대조). 대상은 권한 있는 계정뿐이라 재로그인 비용이 작고, 얻는 것은 확실하다.
--
-- ⚠ **학생(USER)은 건드리지 않는다.** 전원 강제 로그아웃은 공짜가 아니다 — 65명은 아직
--   이메일조차 없어 재로그인 문턱이 높다. 그들의 노출 범위는 자기 계정 하나이고, 수명
--   30일도 설치형(PWA) 사용을 위해 의도적으로 정한 값이다.
--
-- ⚠ 이 마이그레이션은 **1회성 컷오버**다. 재실행되면 관리자가 또 로그아웃되지만 그뿐이고
--   데이터는 안전하다(멱등하지 않을 뿐 파괴적이지 않다).

UPDATE "User"
SET "sessionEpoch" = "sessionEpoch" + 1
WHERE "role" IN ('ADMIN', 'DEVELOPER');
