-- 사업자등록번호 실재 확인 결과 저장 (2026-08-05).
--
-- ## 무엇이 문제였나
--
-- 같은 날 발주·견적서 게이트를 사업자등록번호로 바꾸면서 `isValidBizNo()`(체크섬)를 넣었다.
-- 그런데 **체크섬은 형식만 본다.** 앞 9자리를 아무렇게나 정하고 끝자리만 계산하면 100%
-- 통과한다 — 오타는 막지만 악의는 못 막는다.
--
-- 실재 확인(팝빌 `checkBizInfo`)이 도는 곳은 `createOrderAction` **한 곳뿐**이었다. 그래서
-- 지어낸 번호로도:
--
--   * `canTransact` 통과 → **발주 메뉴가 열리고**
--   * `GET /api/orders/quote` 통과 → **우리 상호·사업자번호·직인이 찍힌 견적서가 나왔다**
--
-- 돈이 나가는 지점(세금계산서 100원, 조회 50원)은 막혀 있었지만 **문서가 나가는 지점은
-- 안 막혀 있었다.** 견적서는 팝빌을 안 부르므로 비용은 0인데, 그게 곧 "검증도 0"이었다.
--
-- ## 저장 시점 1회 조회
--
-- 게이트마다 조회하면 화면을 여는 것만으로 50원씩 나간다(`lookupBizAction` 에서 피한 패턴).
-- 대신 **저장할 때 한 번** 확인하고 결과를 남겨, 게이트는 그 결과를 읽기만 한다.
-- 번호가 바뀌었거나 아직 확인 못 한 경우에만 부르므로 **기업당 50원, 1회**다.
-- `createOrderAction` 은 이미 조회한 결과를 넘겨 이중 과금을 피한다.
--
-- ## 🔴 NULL 과 '미등록'은 다른 값이다
--
--   NULL      = 확인 못 함 (팝빌 미설정 · 일시 장애)  → **통과시킨다**
--   '미등록'  = 조회했더니 없음                       → 차단
--
-- 둘을 뭉뚱그리면 ① 로컬·스테이징(팝빌 미설정)에서 아무도 발주를 못 하고
-- ② 팝빌이 잠깐 죽으면 멀쩡한 기존 기업까지 잠긴다. `createOrderAction` 이 예전부터
-- "조회 실패는 발주를 막지 않는다"로 동작해온 것과 같은 원칙이다.
--
-- 기존 행은 NULL 로 남는다 = "아직 확인 못 함". backfill 하지 않는다 — 확인한 적 없는 것을
-- '정상'으로 채우면 이 컬럼이 거짓말을 하게 되고, 그러면 게이트가 아무 의미도 없어진다.
-- 다음 저장 때 자연스럽게 채워진다.

