-- 세션 개별 무효화 (2026-08-18).
--
-- ## 무엇이 문제였나
--
-- 세션 쿠키가 `<userId>.<HMAC>` 이라 **서명 대상이 userId 뿐**이었다. 그래서:
--
--   * 비밀번호를 바꿔도 **유출된 쿠키가 30일간 그대로 살아 있었다.**
--     비밀번호 변경은 보통 "이 계정이 털린 것 같다"에 대한 대응인데, 정작 공격자의
--     세션은 안 끊겼다. 재설정 메일·관리자 임시 비밀번호 발급도 마찬가지였다.
--   * 정지·탈퇴는 `loginAction` 이 **로그인만** 막는다. 이미 로그인해 둔 세션은 계속 돌았다.
--
-- ## 왜 epoch 인가
--
-- 서버측 세션 저장소를 두면 요청마다 조회가 붙고 만료 정리도 따라온다. 우리 규모에는
-- 과하다. 대신 **세대 번호를 서명 페이로드에 넣고** DB 값과 다르면 거부한다 —
-- 무효화가 `UPDATE ... SET "sessionEpoch" = "sessionEpoch" + 1` 한 줄이 된다.
--
-- 정수를 쓴 이유는 `passwordChangedAt` 같은 타임스탬프보다 비교가 단순하고(정확히 같아야
-- 통과), **비밀번호 말고 다른 이유(정지·탈퇴·역할 변경)로도 끊을 수 있기** 때문이다.
--
-- ## ⚠ 기존 세션은 죽지 않는다 — 의도한 것이다
--
-- 옛 형식(`userId.MAC`, 2조각)을 **epoch 0 으로 받아준다.** 기본값이 0 이라 그대로 통과하고,
-- 그 사용자가 비밀번호를 바꾸는 순간 1 이 되어 옛 쿠키가 죽는다.
-- 서명을 처음 붙일 때(2026-07-31)는 전원 재로그인이 불가피했지만, 이번엔 그럴 이유가 없다 —
-- 강제 로그아웃은 공짜가 아니고 여기서는 얻는 게 없다.
--
-- 기존 행은 DEFAULT 0 으로 채워진다. backfill 하지 않는다.

-- AlterTable
ALTER TABLE "User" ADD COLUMN     "sessionEpoch" INTEGER NOT NULL DEFAULT 0;
