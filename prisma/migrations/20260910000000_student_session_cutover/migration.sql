-- 학생 세션 일괄 무효화 (2026-09-10).
--
-- ## 왜 필요한가
--
-- 같은 배포에서 세션 수명을 뒤집었다 — **학생 30일 → 2시간**(절대 90일 → 12시간),
-- 관리자 8시간 → 7일(절대 24시간 → 30일). `app/session.ts` 주석에 이유가 있다.
--
-- 그런데 **수명은 쿠키가 나른다**(`ttl`·`exp`·`abs` 가 서명 대상 안에 있다). middleware 는
-- Edge 라 DB 를 못 봐서 갱신할 때 쿠키에 적힌 값을 그대로 이어받는다. 즉 **코드만 고치면
-- 이미 발급된 학생 쿠키는 다음 로그인 전까지 30일 그대로**다.
--
-- 이 변경이 겨냥한 대상이 정확히 그것이다 — **지금 실습실·공용 PC 에 열려 있는 세션.**
-- 새 정책은 앞으로 발급될 쿠키에만 적용되므로, 정작 위험한 쪽을 비껴간다.
-- 2026-09-02 관리자 컷오버(`20260902000000_admin_session_cutover`)와 똑같은 구조다.
--
-- ## 그래서 한 번 끊는다
--
-- `sessionEpoch` 를 올리면 그 계정의 모든 세션이 즉시 무효가 된다(`getSessionUserId` 가
-- DB 값과 대조). 학생은 이메일 + 비밀번호로 다시 로그인하면 되고, 그때 2시간짜리 쿠키를
-- 새로 받는다.
--
-- ⚠ **같은 배포에 무한 리다이렉트 수정이 함께 들어간다**(`app/session-expired/route.ts`).
--   그게 없으면 이 UPDATE 는 전원을 루프에 빠뜨린다 — middleware 는 서명만 보므로 세션을
--   유효하다고 판단해 `/dashboard` 로 돌려보내고, 페이지는 epoch 이 어긋나 `/` 로 보낸다.
--   **이 마이그레이션을 그 수정보다 먼저 배포하지 말 것.**
--
-- ⚠ ADMIN·DEVELOPER 는 건드리지 않는다. 그쪽은 수명이 **길어지는** 방향이고, 지금 들고
--   있는 쿠키의 절대 만료가 24시간이라 하루 안에 자연히 재발급된다.
--
-- ⚠ 재실행되면 학생이 또 로그아웃되지만 그뿐이다(멱등하지 않을 뿐 파괴적이지 않다).

UPDATE "User"
SET "sessionEpoch" = "sessionEpoch" + 1
WHERE "role" = 'USER';
